const { pool } = require('../config/database');
const logger = require('../config/logger');
const createCsvWriter = require('csv-writer').createObjectCsvWriter;
const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

// Create reports directory if it doesn't exist
const reportsDir = path.join(__dirname, '../../reports');
if (!fs.existsSync(reportsDir)) {
  fs.mkdirSync(reportsDir, { recursive: true });
}

/**
 * Generate daily report
 * GET /api/reports/daily
 */
const generateDailyReport = async (req, res) => {
  try {
    const date = req.query.date || new Date().toISOString().split('T')[0];

    const [records] = await pool.execute(
      `SELECT 
        lr.id,
        lr.borrowed_date,
        lr.due_date,
        lr.returned_date,
        lr.fine_amount,
        u.name as user_name,
        u.email as user_email,
        b.title as book_title,
        b.author as book_author,
        b.isbn,
        CASE 
          WHEN lr.returned_date IS NOT NULL THEN 'Returned'
          WHEN DATE(lr.borrowed_date) = ? THEN 'Borrowed'
          ELSE 'Active'
        END as transaction_type
      FROM lending_records lr
      JOIN users u ON lr.user_id = u.id
      JOIN books b ON lr.book_id = b.id
      WHERE DATE(lr.borrowed_date) = ? OR DATE(lr.returned_date) = ?
      ORDER BY lr.borrowed_date DESC, lr.returned_date DESC`,
      [date, date, date]
    );

    logger.info(`Daily report generated by admin ${req.user.id} for date: ${date}`);

    res.json({
      success: true,
      data: {
        date,
        total_transactions: records.length,
        records
      }
    });
  } catch (error) {
    logger.error('Generate daily report error:', error);
    res.status(500).json({
      success: false,
      message: 'Server error while generating daily report'
    });
  }
};

/**
 * Generate monthly report
 * GET /api/reports/monthly
 */
const generateMonthlyReport = async (req, res) => {
  try {
    const year = parseInt(req.query.year) || new Date().getFullYear();
    const month = parseInt(req.query.month) || new Date().getMonth() + 1;

    const startDate = `${year}-${String(month).padStart(2, '0')}-01`;
    const endDate = new Date(year, month, 0).toISOString().split('T')[0];

    const [records] = await pool.execute(
      `SELECT 
        lr.id,
        lr.borrowed_date,
        lr.due_date,
        lr.returned_date,
        lr.fine_amount,
        u.name as user_name,
        u.email as user_email,
        b.title as book_title,
        b.author as book_author,
        b.isbn,
        CASE 
          WHEN lr.returned_date IS NOT NULL THEN 'Returned'
          ELSE 'Borrowed'
        END as transaction_type
      FROM lending_records lr
      JOIN users u ON lr.user_id = u.id
      JOIN books b ON lr.book_id = b.id
      WHERE (DATE(lr.borrowed_date) BETWEEN ? AND ?) OR (DATE(lr.returned_date) BETWEEN ? AND ?)
      ORDER BY lr.borrowed_date DESC, lr.returned_date DESC`,
      [startDate, endDate, startDate, endDate]
    );

    // Calculate summary statistics
    const totalBorrows = records.filter(r => r.transaction_type === 'Borrowed').length;
    const totalReturns = records.filter(r => r.transaction_type === 'Returned').length;

    logger.info(`Monthly report generated by admin ${req.user.id} for ${year}-${month}`);

    res.json({
      success: true,
      data: {
        year,
        month,
        start_date: startDate,
        end_date: endDate,
        total_transactions: records.length,
        total_borrows: totalBorrows,
        total_returns: totalReturns,
        records
      }
    });
  } catch (error) {
    logger.error('Generate monthly report error:', error);
    res.status(500).json({
      success: false,
      message: 'Server error while generating monthly report'
    });
  }
};

