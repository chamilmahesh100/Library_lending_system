/**
 * Export daily report as PDF
 * GET /api/reports/daily/export/pdf
 */
const exportDailyReportPDF = async (req, res) => {
  try {
    const date = req.query.date || new Date().toISOString().split('T')[0];

    const [records] = await pool.execute(
      `SELECT 
        lr.id,
        lr.borrowed_date,
        lr.due_date,
        lr.returned_date,
        lr.fine_amount,
        u.name as user_name,
        u.email as user_email,
        b.title as book_title,
        b.author as book_author,
        b.isbn,
        CASE 
          WHEN lr.returned_date IS NOT NULL THEN 'Returned'
          WHEN DATE(lr.borrowed_date) = ? THEN 'Borrowed'
          ELSE 'Active'
        END as transaction_type
      FROM lending_records lr
      JOIN users u ON lr.user_id = u.id
      JOIN books b ON lr.book_id = b.id
      WHERE DATE(lr.borrowed_date) = ? OR DATE(lr.returned_date) = ?
      ORDER BY lr.borrowed_date DESC, lr.returned_date DESC`,
      [date, date, date]
    );

    const filename = `daily_report_${date}.pdf`;
    const filepath = path.join(reportsDir, filename);

    const doc = new PDFDocument();
    const writeStream = fs.createWriteStream(filepath);
    doc.pipe(writeStream);

    // Header
    doc.fontSize(20).text('Daily Library Report', { align: 'center' });
    doc.fontSize(12).text(`Date: ${date}`, { align: 'center' });
    doc.moveDown();

    // Summary
    doc.fontSize(14).text(`Total Transactions: ${records.length}`);
    doc.moveDown();

    // Table header
    doc.fontSize(10);
    let y = doc.y;
    doc.text('ID', 50, y);
    doc.text('User', 80, y);
    doc.text('Book', 200, y);
    doc.text('Borrowed', 350, y);
    doc.text('Returned', 450, y);
    doc.text('Type', 550, y);
    y += 20;
    doc.moveTo(50, y).lineTo(600, y).stroke();
    y += 10;

    // Table rows
    records.forEach((record, index) => {
      if (y > 700) {
        doc.addPage();
        y = 50;
      }
      doc.text(String(record.id), 50, y);
      doc.text(record.user_name.substring(0, 15), 80, y);
      doc.text(record.book_title.substring(0, 20), 200, y);
      doc.text(record.borrowed_date ? new Date(record.borrowed_date).toLocaleDateString() : '', 350, y);
      doc.text(record.returned_date ? new Date(record.returned_date).toLocaleDateString() : '', 450, y);
      doc.text(record.transaction_type, 550, y);
      y += 20;
    });

    doc.end();

    // Wait for PDF to be written
    await new Promise((resolve, reject) => {
      writeStream.on('finish', resolve);
      writeStream.on('error', reject);
    });

    logger.info(`Daily PDF report exported by admin ${req.user.id} for date: ${date}`);

    res.download(filepath, filename, (err) => {
      if (err) {
        logger.error('Error downloading PDF file:', err);
      }
    });
  } catch (error) {
    logger.error('Export daily PDF error:', error);
    res.status(500).json({
      success: false,
      message: 'Server error while exporting PDF report'
    });
  }
};

